"""PDF の 6 要素のアフィン行列（[a b c d e f]、行ベクトルの規約）の演算。

analyze_fills.py と dissect_pikepdf.py が共有する（CTM・テキスト行列の連結）。外部の依存を持たない。
"""


def mat_mul(a, b):
    """行列 a×b（PDF の 6 要素のアフィン、行ベクトルの規約。cm 演算子は新しい行列を左から掛ける）"""
    return [
        a[0] * b[0] + a[1] * b[2],
        a[0] * b[1] + a[1] * b[3],
        a[2] * b[0] + a[3] * b[2],
        a[2] * b[1] + a[3] * b[3],
        a[4] * b[0] + a[5] * b[2] + b[4],
        a[4] * b[1] + a[5] * b[3] + b[5],
    ]